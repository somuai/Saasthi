def _z_line(lms_l, lms_m, lms_s, lms_z):
    """Compute a single z-score line from WHO LMS parameters."""
    if lms_l == 0:
        return lms_m * (lms_s * lms_z).__exp__()
    return lms_m * (1 + lms_l * lms_s * lms_z) ** (1.0 / lms_l)


class Command(BaseCommand):
    help = "Seed WHO Child Growth Standards reference data"

    def handle(self, *args, **options):
        created = 0
        for (measurement_type, sex), rows in WHO_LMS.items():
            sex_db = "male" if sex == "Male" else "female"
            for age_months, lms_l, lms_m, lms_s in rows:
                _, _ = WHOGrowthReference.objects.update_or_create(
                    sex=sex_db,
                    age_months=age_months,
                    measurement_type=measurement_type,
                    defaults={
                        "sd_minus_3": _z_line(lms_l, lms_m, lms_s, -3),
                        "sd_minus_2": _z_line(lms_l, lms_m, lms_s, -2),
                        "sd_minus_1": _z_line(lms_l, lms_m, lms_s, -1),
                        "median": _z_line(lms_l, lms_m, lms_s, 0),
                        "sd_plus_1": _z_line(lms_l, lms_m, lms_s, 1),
                        "sd_plus_2": _z_line(lms_l, lms_m, lms_s, 2),
                        "sd_plus_3": _z_line(lms_l, lms_m, lms_s, 3),
                    },
                )
                created += 1
        self.stdout.write(self.style.SUCCESS(f"Seeded {created} WHO growth reference rows"))

        self.stdout.write(
            dedent("""\
            NOTE: Only weight-for-age and height-for-age are seeded.
            For weight-for-height, download the full WHO data from:
              https://www.who.int/tools/child-growth-standards/standards
            Then insert rows with measurement_type='wfh'.
            """)
        )
