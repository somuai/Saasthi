import { useEffect, useState } from "react";
import { useSelector } from "react-redux";

export const DEFAULT_LOCALE = "hi";
export const FALLBACK_LOCALE = "en";
export const SUPPORTED_LOCALES = new Set(["hi", "en", "bn", "ta", "te", "kn"]);

let runtimeLocale = DEFAULT_LOCALE;
const listeners = new Set();

export function normalizeLocale(locale) {
  const next = typeof locale === "string" ? locale.trim().toLowerCase() : "";
  return SUPPORTED_LOCALES.has(next) ? next : DEFAULT_LOCALE;
}

export function getCurrentLocale() {
  return runtimeLocale;
}

export function setRuntimeLocale(locale) {
  const next = normalizeLocale(locale);
  if (runtimeLocale === next) return runtimeLocale;
  runtimeLocale = next;
  listeners.forEach((listener) => listener(runtimeLocale));
  return runtimeLocale;
}

export function subscribeLocale(listener) {
  listeners.add(listener);
  return () => listeners.delete(listener);
}

export function useLocale() {
  const userLocale = useSelector((state) => state.auth?.user?.language);
  const [locale, setLocale] = useState(getCurrentLocale());

  useEffect(() => subscribeLocale(setLocale), []);

  useEffect(() => {
    if (userLocale) setRuntimeLocale(userLocale);
  }, [userLocale]);

  return locale;
}

