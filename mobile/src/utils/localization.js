// Devanagari Unicode range check — detects if a string contains any Hindi characters
const DEVANAGARI_RE = /[\u0900-\u097F]/;
function hasHindi(text) {
  return DEVANAGARI_RE.test(text);
}

// Pre-sorted replacement pairs (longest Hindi key first) to prevent partial matches
const REPLACEMENTS = Object.entries(HINDI_TO_BENGALI).sort((a, b) => b[0].length - a[0].length);

export function translateHindiText(value, locale = getCurrentLocale()) {
  if (typeof value !== "string" || normalizeLocale(locale) !== "bn" || !hasHindi(value)) return value;
  if (HINDI_TO_BENGALI[value]) return HINDI_TO_BENGALI[value];
  return REPLACEMENTS.reduce((text, [hi, bn]) => text.split(hi).join(bn), value);
}

export function localizeEntry(entry, locale = getCurrentLocale()) {
  if (!entry) return "";
  if (typeof entry === "string") return translateHindiText(entry, locale);
  const normalized = normalizeLocale(locale);
  if (entry[normalized]) return entry[normalized];
  if (normalized === "bn" && entry.hi) return translateHindiText(entry.hi, normalized);
  return entry.hi || entry[FALLBACK_LOCALE] || "";
}

export function localizePair(hi, en, locale = getCurrentLocale()) {
  const normalized = normalizeLocale(locale);
  if (normalized === "en") return en || hi || "";
  const primary = normalized === "bn" ? translateHindiText(hi, normalized) : hi;
  return en ? `${primary} / ${en}` : primary;
}
